function toPath(points: ReadonlyArray<readonly [number, number]>): string {
    const commands = points.map(([lon, lat], index) => {
        const [x, y] = project(lon, lat);
        return `${index === 0 ? 'M' : 'L'}${x.toFixed(2)} ${y.toFixed(2)}`;
    });
    return `${commands.join(' ')} Z`;
}

